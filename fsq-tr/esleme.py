# Ülke mutfakları: Restaurant altında listede olmayan her şey -> dunya_mutfagi
DUNYA_ISTISNA = {"Buffet", "Bistro", "Gastropub", "Theme Restaurant", "Halal Restaurant", "Turkish Restaurant"}


def esle(etiket: str):
    parcalar = etiket.split(" > ")
    for i in range(len(parcalar), 0, -1):
        anahtar = " > ".join(parcalar[:i])
        if anahtar in K:
            v = K[anahtar]
            if v == ATLA:
                return ("", None, True)
            kat, tur = v
            # Restoran altında tanımsız alt dal -> dünya mutfağı
            if anahtar == "Dining and Drinking > Restaurant" and len(parcalar) > 2 and parcalar[2] not in DUNYA_ISTISNA:
                return ("restoran", "dunya_mutfagi", False)
            return (kat, tur, False)
    if parcalar[0] == "Dining and Drinking":
        return ("restoran", None, False)
    return ("diger", None, False)


